function fail(message, code) {
  const error = new Error(message);
  error.code = code;
  throw error;
}

function contractFor(id) {
  const contract = CONTRACTS.find((item) => item.id === id);
  if (!contract) fail('알 수 없는 의뢰입니다.', 'INVALID_CONTRACT');
  return contract;
}

function equipmentFor(id) {
  const equipment = EQUIPMENT.find((item) => item.id === id);
  if (!equipment) fail('알 수 없는 장비입니다.', 'INVALID_EQUIPMENT');
  return equipment;
}

function validateTeam(team) {
  if (!team || !Number.isInteger(team.washers) || !Number.isInteger(team.haulers)
    || team.washers < 1 || team.haulers < 1 || team.washers + team.haulers !== WORKERS) {
    fail('세척과 운반에 최소 1명씩, 총 4명을 배치해야 합니다.', 'INVALID_TEAM');
  }
  return { washers: team.washers, haulers: team.haulers };
}

function validatePlan(contractId, team, equipmentId) {
  const contract = contractFor(contractId);
  const equipment = equipmentFor(equipmentId);
  const checkedTeam = validateTeam(team);
  if (contract.recovery && equipment.id !== 'none') {
    fail('복구 의뢰는 선투입 비용 없는 기본 도구로 진행합니다.', 'RECOVERY_BASIC_TOOLS');
  }
  return { contract, equipment, team: checkedTeam };
}

export function createCompany() {
  return { cash: 180, active: null, lastReport: null, completed: 0 };
}

function makeActive(contract, team, equipment, startCash) {
  return {
    contractId: contract.id, team, equipmentId: equipment.id,
    elapsed: 0, cleaned: 0, carried: 0, queue: 0, wages: 0,
    blockedSeconds: 0, done: false, blocked: false, bottleneck: null,
    estimatedProfit: 0, estimatedDuration: 0, startCash,
    deferredWages: contract.recovery, reassignments: 0,
  };
}

function ratesFor(active, equipment) {
  return {
    clean: active.team.washers * RATES.clean * equipment.cleanMultiplier,
    haul: active.team.haulers * RATES.haul * equipment.haulMultiplier,
  };
}

function updateStatus(active, contract, equipment) {
  active.queue = Math.max(0, active.cleaned * contract.totalCarry / contract.totalClean - active.carried);
  if (active.cleaned >= contract.totalClean - EPSILON && active.carried >= contract.totalCarry - EPSILON) {
    active.cleaned = contract.totalClean;
    active.carried = contract.totalCarry;
    active.queue = 0;
    active.done = true;
    active.blocked = false;
    active.bottleneck = null;
    return;
  }
  const rates = ratesFor(active, equipment);
  const generation = rates.clean * contract.totalCarry / contract.totalClean;
  active.blocked = active.cleaned < contract.totalClean - EPSILON
    && active.queue >= contract.queueCapacity - EPSILON && generation > rates.haul + EPSILON;
  active.bottleneck = active.cleaned >= contract.totalClean - EPSILON || generation > rates.haul + EPSILON
    ? 'haul' : 'clean';
}

// This is an event-based fluid pipeline: waste is generated by cleaning and hauled
// concurrently. At a full stockpile, cleaners alternate work and waiting. Their
// aggregate rate is limited by hauling; blockedSeconds counts equivalent idle
// time, not the entire time spent working beside a full stockpile.
// Events are stockpile full/empty, cleaning complete, and hauling complete.
// The result is independent of the caller's frame rate or chosen time step.
export function advance(company, seconds) {
  if (!Number.isFinite(seconds) || seconds < 0) fail('진행 시간은 0 이상의 유한수여야 합니다.', 'INVALID_TIME');
  const active = company.active;
  if (!active || active.done || seconds === 0) return company;
  const contract = contractFor(active.contractId);
  const equipment = equipmentFor(active.equipmentId);
  const rates = ratesFor(active, equipment);
  const ratio = contract.totalCarry / contract.totalClean;
  const generation = rates.clean * ratio;
  let remaining = seconds;

  while (remaining > EPSILON && !active.done) {
    updateStatus(active, contract, equipment);
    if (active.done) break;
    let duration;
    let cleanRate = rates.clean;
    let carryRate = rates.haul;
    let idleFraction = 0;
    if (active.cleaned >= contract.totalClean - EPSILON) {
      cleanRate = 0;
      duration = Math.min(remaining, (contract.totalCarry - active.carried) / rates.haul);
    } else if (active.blocked) {
      cleanRate = rates.haul / ratio;
      idleFraction = 1 - cleanRate / rates.clean;
      duration = Math.min(remaining, (contract.totalClean - active.cleaned) / cleanRate);
    } else {
      duration = Math.min(remaining, (contract.totalClean - active.cleaned) / rates.clean);
      if (generation > rates.haul + EPSILON) {
        duration = Math.min(duration, (contract.queueCapacity - active.queue) / (generation - rates.haul));
      } else if (generation < rates.haul - EPSILON && active.queue > EPSILON) {
        duration = Math.min(duration, active.queue / (rates.haul - generation));
      } else if (active.queue <= EPSILON) {
        carryRate = Math.min(rates.haul, generation);
      }
    }
    if (duration <= 0) fail('작업 진행 이벤트 계산에 실패했습니다.', 'SIMULATION_ERROR');
    active.cleaned = Math.min(contract.totalClean, active.cleaned + cleanRate * duration);
    active.carried = Math.min(contract.totalCarry, active.carried + carryRate * duration);
    active.elapsed += duration;
    const wage = WORKERS * RATES.wage * duration;
    active.wages += wage;
    active.blockedSeconds += idleFraction * duration;
    if (!active.deferredWages) company.cash -= wage;
    remaining -= duration;
    updateStatus(active, contract, equipment);
  }
  return company;
}

function reportFor(active) {
  const contract = contractFor(active.contractId);
  const equipment = equipmentFor(active.equipmentId);
  const profit = contract.fee + contract.salvage - contract.supplies - equipment.cost - active.wages;
  let cause;
  if (contract.recovery) {
    cause = '선투입 없이 의뢰비 수령 후 임금을 정산했습니다.';
  } else if (active.blockedSeconds > 1) {
    cause = `운반 적체에 따른 세척 대기 약 ${active.blockedSeconds.toFixed(1)}초(대기 비율을 시간으로 환산). 인건비가 손익에 반영됐습니다.`;
  } else {
    cause = '폐품 적체 없이 작업했습니다. 작업 시간과 현장 임대료가 손익에 반영됐습니다.';
  }
  return {
    contractId: contract.id, contractName: contract.name,
    fee: contract.fee, salvage: contract.salvage, wages: active.wages,
    supplies: contract.supplies, equipmentCost: equipment.cost,
    totalCost: contract.supplies + equipment.cost + active.wages,
    revenue: contract.fee + contract.salvage, profit, duration: active.elapsed,
    blockedSeconds: active.blockedSeconds, cause,
    estimatedProfit: active.estimatedProfit, estimatedDuration: active.estimatedDuration,
    startCash: active.startCash, finalTeam: { ...active.team },
    equipmentId: equipment.id, reassignments: active.reassignments,
  };
}

export function estimate(contractId, team, equipmentId = 'none') {
  const plan = validatePlan(contractId, team, equipmentId);
  const simulation = createCompany();
  simulation.active = makeActive(plan.contract, plan.team, plan.equipment, 0);
  advance(simulation, 1_000_000);
  const report = reportFor(simulation.active);
  report.estimatedProfit = report.profit;
  report.estimatedDuration = report.duration;
  return report;
}

export function startJob(company, contractId, team, equipmentId = 'none') {
  if (company.active) fail('현재 의뢰를 정산한 뒤 다음 의뢰를 시작할 수 있습니다.', 'JOB_ACTIVE');
  if (!Number.isFinite(company.cash)) fail('회사 잔고가 올바르지 않습니다.', 'INVALID_COMPANY');
  const plan = validatePlan(contractId, team, equipmentId);
  const expected = estimate(contractId, team, equipmentId);
  if (!plan.contract.recovery && company.cash + EPSILON < expected.totalCost) {
    fail(`예상 비용 ${expected.totalCost.toFixed(1)}G를 충당할 잔고가 부족합니다. 기본 도구·외상 정산 의뢰로 복구할 수 있습니다.`, 'INSUFFICIENT_FUNDS');
  }
  company.active = makeActive(plan.contract, plan.team, plan.equipment, company.cash);
  company.active.estimatedProfit = expected.profit;
  company.active.estimatedDuration = expected.duration;
  company.cash -= plan.contract.supplies + plan.equipment.cost;
  updateStatus(company.active, plan.contract, plan.equipment);
  return company;
}

export function reassign(company, team) {
  if (!company.active || company.active.done) fail('작업 중에만 인력을 재배치할 수 있습니다.', 'NO_RUNNING_JOB');
  const checked = validateTeam(team);
  if (checked.washers !== company.active.team.washers || checked.haulers !== company.active.team.haulers) {
    company.active.team = checked;
    company.active.reassignments += 1;
  }
  updateStatus(company.active, contractFor(company.active.contractId), equipmentFor(company.active.equipmentId));
  return company;
}

export function settle(company) {
  if (!company.active) fail('정산할 의뢰가 없습니다.', 'NO_JOB');
  if (!company.active.done) fail('세척과 운반을 모두 끝낸 뒤 정산할 수 있습니다.', 'JOB_INCOMPLETE');
  const report = reportFor(company.active);
  company.cash += report.revenue - (company.active.deferredWages ? report.wages : 0);
  report.endCash = company.cash;
  company.lastReport = report;
  company.completed += 1;
  company.active = null;
  return company;
}
